# Laskin v1.0
def yhteenlasku(a, b):
    return a + b
def vähennyslasku(a, b):
    return a - b
def kertolasku(a, b):
    return a * b
def jakolasku (a, b):
    return a / b
print ("Laskin vl1.0")
print ("5 + 3 =", yhteenlasku(5, 3))
print ("10 - 4 =", vähennyslasku(10, 4))
print ("6 * 7 =", kertolasku(6, 7))
print ("8 / 4 =", jakolasku(8, 4))
